//! `atlas-duck-docgen`: Markdown user guide to static help sets (M16, PD-326).
//!
//! ```text
//! atlas-duck-docgen --src docs/user-guide --desktop-out app/ui/public/help \
//!                   --server-out app/ui/public-server/docs [--check]
//! ```
//!
//! Without `--check` the two output directories are made to equal the generated sets (stale files
//! are deleted: the directories belong to the generator). With `--check` nothing is written and
//! the exit code is 1 when a file is missing, stale or different.

#![deny(clippy::unwrap_used, clippy::expect_used)]

mod frontmatter;
mod render;
mod search;
mod site;
#[cfg(test)]
mod tests;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Component, Path, PathBuf};
use std::process::ExitCode;

use render::Set;
use site::Files;

struct Args {
    src: PathBuf,
    desktop_out: PathBuf,
    server_out: PathBuf,
    check: bool,
}

fn parse_args(args: impl Iterator<Item = String>) -> Result<Args, String> {
    let (mut src, mut desktop, mut server, mut check) = (None, None, None, false);
    let mut args = args;
    while let Some(arg) = args.next() {
        let mut value = |name: &str| {
            args.next()
                .map(PathBuf::from)
                .ok_or_else(|| format!("{name} needs a value"))
        };
        match arg.as_str() {
            "--src" => src = Some(value("--src")?),
            "--desktop-out" => desktop = Some(value("--desktop-out")?),
            "--server-out" => server = Some(value("--server-out")?),
            "--check" => check = true,
            other => return Err(format!("unknown argument `{other}`")),
        }
    }
    let need = |v: Option<PathBuf>, name: &str| v.ok_or_else(|| format!("{name} is required"));
    Ok(Args {
        src: need(src, "--src")?,
        desktop_out: need(desktop, "--desktop-out")?,
        server_out: need(server, "--server-out")?,
        check,
    })
}

/// Every file below `dir` (`/`-separated relative path -> bytes, CRLF folded to LF so a Windows
/// checkout with `core.autocrlf` compares equal to the generated bytes).
fn read_tree(dir: &Path) -> Result<Files, String> {
    fn walk(root: &Path, dir: &Path, out: &mut Files) -> Result<(), String> {
        let io = |e: std::io::Error| format!("{}: {e}", dir.display());
        for entry in fs::read_dir(dir).map_err(io)? {
            let entry = entry.map_err(io)?;
            let path = entry.path();
            let kind = entry.file_type().map_err(io)?;
            if kind.is_symlink() {
                // A link (symlink or junction) is never followed: what it points at is not ours.
                continue;
            }
            if kind.is_dir() {
                walk(root, &path, out)?;
            } else if kind.is_file() {
                let rel = path.strip_prefix(root).map_err(|e| e.to_string())?;
                let name = rel
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy())
                    .collect::<Vec<_>>()
                    .join("/");
                let bytes = fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
                out.insert(name, fold_crlf(bytes));
            }
        }
        Ok(())
    }
    let mut out = BTreeMap::new();
    if dir.is_dir() {
        walk(dir, dir, &mut out)?;
    }
    Ok(out)
}

fn fold_crlf(bytes: Vec<u8>) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    for (i, b) in bytes.iter().enumerate() {
        if *b == b'\r' && bytes.get(i + 1) == Some(&b'\n') {
            continue;
        }
        out.push(*b);
    }
    out
}

/// Differences between the generated `files` and what is on disk below `dir`.
fn drift(dir: &Path, files: &Files) -> Result<Vec<String>, String> {
    let disk = read_tree(dir)?;
    let mut out = Vec::new();
    for (name, bytes) in files {
        match disk.get(name) {
            None => out.push(format!("{}: missing", dir.join(name).display())),
            Some(d) if d != bytes => out.push(format!("{}: differs", dir.join(name).display())),
            Some(_) => {}
        }
    }
    for name in disk.keys().filter(|n| !files.contains_key(*n)) {
        out.push(format!(
            "{}: stale (not generated)",
            dir.join(name).display()
        ));
    }
    if dir.is_dir() {
        let mut empty = Vec::new();
        empty_dirs(dir, dir, &mut empty)?;
        for d in empty {
            out.push(format!("{}: stale empty directory", d.display()));
        }
    }
    Ok(out)
}

/// The topmost directories below `root` that hold no file and no link (write mode prunes them).
/// Returns whether `dir` itself is such a directory.
fn empty_dirs(dir: &Path, root: &Path, out: &mut Vec<PathBuf>) -> Result<bool, String> {
    let io = |e: std::io::Error| format!("{}: {e}", dir.display());
    let mut all_empty = true;
    let mut found = Vec::new();
    for entry in fs::read_dir(dir).map_err(io)? {
        let entry = entry.map_err(io)?;
        let kind = entry.file_type().map_err(io)?;
        if kind.is_dir() && !kind.is_symlink() {
            if !empty_dirs(&entry.path(), root, &mut found)? {
                all_empty = false;
            }
        } else {
            all_empty = false;
        }
    }
    if all_empty && dir != root {
        out.push(dir.to_path_buf());
        return Ok(true);
    }
    out.append(&mut found);
    Ok(all_empty)
}

/// Removes empty directories below `dir` (not `dir` itself); links are not entered.
fn prune_empty(dir: &Path, root: &Path) -> Result<(), String> {
    let io = |e: std::io::Error| format!("{}: {e}", dir.display());
    for entry in fs::read_dir(dir).map_err(io)? {
        let entry = entry.map_err(io)?;
        if entry.file_type().map_err(io)?.is_dir() {
            prune_empty(&entry.path(), root)?;
        }
    }
    if dir != root && fs::read_dir(dir).map_err(io)?.next().is_none() {
        fs::remove_dir(dir).map_err(io)?;
    }
    Ok(())
}

/// `path` made absolute, `..` collapsed, and its longest existing prefix canonicalized (an out dir
/// need not exist yet).
fn resolve(path: &Path) -> Result<PathBuf, String> {
    let abs = std::path::absolute(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut norm = PathBuf::new();
    for c in abs.components() {
        match c {
            Component::ParentDir => {
                norm.pop();
            }
            Component::CurDir => {}
            c => norm.push(c),
        }
    }
    let mut rest = Vec::new();
    let mut head = norm.as_path();
    while !head.exists() {
        let (Some(name), Some(parent)) = (head.file_name(), head.parent()) else {
            break;
        };
        rest.push(name.to_owned());
        head = parent;
    }
    let mut out = fs::canonicalize(head).map_err(|e| format!("{}: {e}", head.display()))?;
    out.extend(rest.iter().rev());
    Ok(out)
}

/// Windows paths are case-insensitive, so overlap is judged on lower-cased paths there (an out dir
/// that does not exist yet keeps whatever case it was typed in).
fn fold_case(path: &Path) -> PathBuf {
    if cfg!(windows) {
        PathBuf::from(path.to_string_lossy().to_lowercase())
    } else {
        path.to_path_buf()
    }
}

/// The generator deletes whatever it did not generate below an out dir, so an out dir that is, holds
/// or lies inside the sources (or the other out dir) is refused.
fn check_disjoint(src: &Path, desktop: &Path, server: &Path) -> Result<(), String> {
    let dirs = [
        ("--src", resolve(src)?),
        ("--desktop-out", resolve(desktop)?),
        ("--server-out", resolve(server)?),
    ];
    for (i, (a_name, a)) in dirs.iter().enumerate() {
        for (b_name, b) in &dirs[i + 1..] {
            let (fa, fb) = (fold_case(a), fold_case(b));
            if fa.starts_with(&fb) || fb.starts_with(&fa) {
                return Err(format!(
                    "{a_name} ({}) and {b_name} ({}) overlap",
                    a.display(),
                    b.display()
                ));
            }
        }
    }
    Ok(())
}

fn write_tree(dir: &Path, files: &Files) -> Result<(), String> {
    let disk = read_tree(dir)?;
    for name in disk.keys().filter(|n| !files.contains_key(*n)) {
        let path = dir.join(name);
        fs::remove_file(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    if dir.is_dir() {
        prune_empty(dir, dir)?;
    }
    for (name, bytes) in files {
        if disk.get(name) == Some(bytes) {
            continue;
        }
        let path = dir.join(name);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        fs::write(&path, bytes).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(())
}

fn run() -> Result<ExitCode, String> {
    let args = parse_args(std::env::args().skip(1))?;
    check_disjoint(&args.src, &args.desktop_out, &args.server_out)?;
    let sources = site::load(&args.src)?;
    let mut problems = Vec::new();
    for (set, out) in [
        (Set::Desktop, &args.desktop_out),
        (Set::Server, &args.server_out),
    ] {
        let files = site::generate(&sources, set)?;
        if args.check {
            problems.extend(drift(out, &files)?);
        } else {
            write_tree(out, &files)?;
        }
    }
    if problems.is_empty() {
        return Ok(ExitCode::SUCCESS);
    }
    for p in &problems {
        eprintln!("{p}");
    }
    eprintln!("atlas-duck-docgen: the committed help sets are out of date; run it without --check");
    Ok(ExitCode::FAILURE)
}

fn main() -> ExitCode {
    run().unwrap_or_else(|e| {
        eprintln!("atlas-duck-docgen: {e}");
        ExitCode::from(2)
    })
}
